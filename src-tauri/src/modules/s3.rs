/// A child node of a listing: either a sub-prefix ("folder") or an object.
#[derive(Serialize, Debug)]
pub struct S3Entry {
    /// Display name (last path segment, prefixes keep the trailing `/`).
    pub name: String,
    /// Full key (objects) or prefix (folders) relative to the bucket.
    pub key: String,
    pub is_prefix: bool,
    /// Object size in bytes; `None` for prefixes.
    pub size: Option<i64>,
}

/// List the immediate children of `prefix` in `bucket` (delimiter `/`), so the
/// UI can lazily expand one tree level at a time. An empty `bucket` lists the
/// account's buckets instead.
#[tauri::command]
pub async fn s3_list(
    app: AppHandle,
    state: tauri::State<'_, S3State>,
    secrets: tauri::State<'_, SecretsState>,
    id: String,
    bucket: String,
    prefix: String,
) -> Result<Vec<S3Entry>, String> {
    let conn = resolve(&app, &state, &secrets, &id).await?;
    let client = sdk_client(&conn).await;

    // Bucket-level listing.
    if bucket.is_empty() {
        let out = client
            .list_buckets()
            .send()
            .await
            .map_err(|e| aws_err("list buckets", e))?;
        let mut entries: Vec<S3Entry> = out
            .buckets()
            .iter()
            .filter_map(|b| b.name().map(|n| n.to_string()))
            .map(|name| S3Entry {
                key: name.clone(),
                name,
                is_prefix: true,
                size: None,
            })
            .collect();
        entries.sort_by(|a, b| a.name.cmp(&b.name));
        return Ok(entries);
    }

    let out = client
        .list_objects_v2()
        .bucket(&bucket)
        .prefix(&prefix)
        .delimiter("/")
        .max_keys(LIST_PAGE_SIZE)
        .send()
        .await
        .map_err(|e| aws_err("list objects", e))?;

    let mut entries: Vec<S3Entry> = Vec::new();

    // Sub-prefixes ("folders").
    for cp in out.common_prefixes() {
        if let Some(p) = cp.prefix() {
            let trimmed = p.strip_suffix('/').unwrap_or(p);
            let name = trimmed.rsplit('/').next().unwrap_or(trimmed).to_string();
            entries.push(S3Entry {
                name: format!("{name}/"),
                key: p.to_string(),
                is_prefix: true,
                size: None,
            });
        }
    }
    // Objects at this level (skip the prefix placeholder key itself).
    for obj in out.contents() {
        if let Some(k) = obj.key() {
            if k == prefix {
                continue;
            }
            let name = k.rsplit('/').next().unwrap_or(k).to_string();
            entries.push(S3Entry {
                name,
                key: k.to_string(),
                is_prefix: false,
                size: obj.size(),
            });
        }
    }
    Ok(entries)
}

