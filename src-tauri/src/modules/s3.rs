// Client builders
// ---------------------------------------------------------------------------

/// Build an `aws-sdk-s3` client used for listing and byte fetches.
async fn sdk_client(conn: &ResolvedConnection) -> aws_sdk_s3::Client {
    use aws_sdk_s3::config::{Credentials, Region};

    let creds = Credentials::new(
        conn.secret.access_key_id.clone(),
        conn.secret.secret_access_key.clone(),
        conn.secret.session_token.clone(),
        None,
        "terax-s3",
    );

    let mut builder = aws_sdk_s3::config::Builder::new()
        .behavior_version(aws_sdk_s3::config::BehaviorVersion::latest())
        .region(Region::new(conn.meta.region.clone()))
        .credentials_provider(creds);

    if let Some(ep) = &conn.meta.endpoint {
        builder = builder.endpoint_url(ep.clone());
    }
    if conn.meta.force_path_style {
        builder = builder.force_path_style(true);
    }

    aws_sdk_s3::Client::from_conf(builder.build())
}

/// Build an `object_store` S3 store for the async parquet ranged reader.
fn object_store(
    conn: &ResolvedConnection,
    bucket: &str,
) -> Result<object_store::aws::AmazonS3, String> {
    use object_store::aws::AmazonS3Builder;

    let mut b = AmazonS3Builder::new()
        .with_bucket_name(bucket)
        .with_region(&conn.meta.region)
        .with_access_key_id(&conn.secret.access_key_id)
        .with_secret_access_key(&conn.secret.secret_access_key);

    if let Some(ep) = &conn.meta.endpoint {
        b = b.with_endpoint(ep).with_allow_http(ep.starts_with("http://"));
    }
    if conn.meta.force_path_style {
        b = b.with_virtual_hosted_style_request(false);
    }
    if let Some(tok) = &conn.secret.session_token {
        b = b.with_token(tok);
    }

    b.build().map_err(|e| format!("object_store: {e}"))
}

