/// Bytes of a small object for inline preview, base64-encoded for the JSON IPC
/// boundary. Rejects objects over [`MAX_INLINE_BYTES`] — those should use the
/// temp-cache download path.
#[derive(Serialize, Debug)]
pub struct S3Bytes {
    /// base64 of the raw object bytes.
    pub base64: String,
    /// `Content-Type` reported by S3, if any.
    pub content_type: Option<String>,
    pub size: i64,
}

#[tauri::command]
pub async fn s3_get_object_bytes(
    app: AppHandle,
    state: tauri::State<'_, S3State>,
    secrets: tauri::State<'_, SecretsState>,
    id: String,
    bucket: String,
    key: String,
) -> Result<S3Bytes, String> {
    let conn = resolve(&app, &state, &secrets, &id).await?;
    let client = sdk_client(&conn).await;

    let out = client
        .get_object()
        .bucket(&bucket)
        .key(&key)
        .send()
        .await
        .map_err(|e| aws_err("get object", e))?;

    let size = out.content_length().unwrap_or(0);
    if size as u64 > MAX_INLINE_BYTES {
        return Err(format!(
            "object is {size} bytes; too large for inline preview (max {MAX_INLINE_BYTES})"
        ));
    }
    let content_type = out.content_type().map(|s| s.to_string());
    let data = out
        .body
        .collect()
        .await
        .map_err(|e| format!("read body: {e}"))?
        .into_bytes();

    Ok(S3Bytes {
        base64: base64_encode(&data),
        content_type,
        size: data.len() as i64,
    })
}

// ---------------------------------------------------------------------------
// Temp-cache download (formats that can't be ranged over S3)
// ---------------------------------------------------------------------------

/// Download an object to a stable temp path keyed by connection/bucket/key and
/// return the local path. Reused on subsequent opens (the cache file persists
/// for the process lifetime). SQLite (random-access) and CSV (no row index) use
/// this so the local `data_*` engine can open them.
#[tauri::command]
pub async fn s3_download_to_cache(
    app: AppHandle,
    state: tauri::State<'_, S3State>,
    secrets: tauri::State<'_, SecretsState>,
    id: String,
    bucket: String,
    key: String,
) -> Result<String, String> {
    use tokio::io::AsyncWriteExt;

    let conn = resolve(&app, &state, &secrets, &id).await?;
    let client = sdk_client(&conn).await;

    let dir = app
        .path()
        .app_cache_dir()
        .map_err(|e| e.to_string())?
        .join("s3-cache")
        .join(safe_component(&id))
        .join(safe_component(&bucket));
    tokio::fs::create_dir_all(&dir)
        .await
        .map_err(|e| e.to_string())?;
    // Flatten the key to a single filename, preserving the extension so the FE
    // format detector still recognizes it.
    let fname = safe_component(&key);
    let dest = dir.join(&fname);

    let mut out = client
        .get_object()
        .bucket(&bucket)
        .key(&key)
        .send()
        .await
        .map_err(|e| aws_err("get object", e))?;

    let mut file = tokio::fs::File::create(&dest)
        .await
        .map_err(|e| format!("create cache file: {e}"))?;
    while let Some(chunk) = out
        .body
        .try_next()
        .await
        .map_err(|e| format!("download: {e}"))?
    {
        file.write_all(&chunk).await.map_err(|e| e.to_string())?;
    }
    file.flush().await.map_err(|e| e.to_string())?;

    Ok(super::fs::to_canon(&dest))
}

// ---------------------------------------------------------------------------
// Parquet — ranged paging directly from S3
// ---------------------------------------------------------------------------

/// Page a Parquet object **without downloading the whole file**: the async
/// object-store reader fetches only the row groups / byte ranges the requested
/// window touches. Mirrors `data_parquet_preview`'s wire format so the same
/// `DataPane` renders both local and S3 parquet. Search/sort are intentionally
/// unsupported here (they require a full scan, which defeats ranged reads — the
/// UI should fall back to the temp-cache path for those).
#[tauri::command]
pub async fn s3_parquet_preview(
    app: AppHandle,
    state: tauri::State<'_, S3State>,
    secrets: tauri::State<'_, SecretsState>,
    id: String,
    bucket: String,
    key: String,
    limit: u32,
    offset: u32,
    _search: Option<String>,
    _sort: Option<SortSpec>,
) -> Result<DataPreview, String> {
    use futures_util::StreamExt;
    use object_store::ObjectStore;
    use parquet::arrow::arrow_reader::ArrowReaderMetadata;
    use parquet::arrow::async_reader::{ParquetObjectReader, ParquetRecordBatchStreamBuilder};

    let conn = resolve(&app, &state, &secrets, &id).await?;
    let store = std::sync::Arc::new(object_store(&conn, &bucket)?);
    let path = object_store::path::Path::from(key.as_str());

    let meta = store
        .head(&path)
        .await
        .map_err(|e| format!("stat object: {e}"))?;
    let reader = ParquetObjectReader::new(store, meta);

    let arrow_meta = ArrowReaderMetadata::load_async(
        &mut reader.clone(),
        Default::default(),
    )
    .await
    .map_err(|e| format!("parquet meta: {e}"))?;

    let file_total = arrow_meta
        .metadata()
        .file_metadata()
        .num_rows()
        .max(0) as u64;

    let limit = limit.clamp(1, 5_000) as usize;
    let offset = offset as usize;

    let builder =
        ParquetRecordBatchStreamBuilder::new_with_metadata(reader, arrow_meta.clone());
    let columns: Vec<String> = builder
        .schema()
        .fields()
        .iter()
        .map(|f| f.name().to_string())
        .collect();

    // `with_offset`/`with_limit` push the row window into the reader so only the
    // touched row groups are fetched from S3.
    let mut stream = builder
        .with_offset(offset)
        .with_limit(limit)
        .build()
        .map_err(|e| format!("parquet stream: {e}"))?;

    let mut rows: Vec<Vec<Option<String>>> = Vec::new();
    while let Some(batch) = stream.next().await {
        let batch = batch.map_err(|e| format!("parquet batch: {e}"))?;
        let n = batch.num_rows();
        let cols = batch.columns();
        for r in 0..n {
            let mut cells = Vec::with_capacity(cols.len());
            for col in cols {
                cells.push(super::fs::data::arrow_value_to_string(col, r));
            }
            rows.push(cells);
        }
    }

    Ok(DataPreview {
        columns,
        rows,
        total: Some(file_total),
    })
}

// ---------------------------------------------------------------------------
// base64 (no extra dep — small std impl)
// ---------------------------------------------------------------------------

fn base64_encode(input: &[u8]) -> String {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(input.len().div_ceil(3) * 4);
    for chunk in input.chunks(3) {
        let b = [
            chunk[0],
            *chunk.get(1).unwrap_or(&0),
            *chunk.get(2).unwrap_or(&0),
        ];
        let n = ((b[0] as u32) << 16) | ((b[1] as u32) << 8) | (b[2] as u32);
        out.push(T[((n >> 18) & 63) as usize] as char);
        out.push(T[((n >> 12) & 63) as usize] as char);
        out.push(if chunk.len() > 1 {
            T[((n >> 6) & 63) as usize] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            T[(n & 63) as usize] as char
        } else {
            '='
        });
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn base64_matches_known_vectors() {
        assert_eq!(base64_encode(b""), "");
        assert_eq!(base64_encode(b"f"), "Zg==");
        assert_eq!(base64_encode(b"fo"), "Zm8=");
        assert_eq!(base64_encode(b"foo"), "Zm9v");
        assert_eq!(base64_encode(b"foob"), "Zm9vYg==");
        assert_eq!(base64_encode(b"fooba"), "Zm9vYmE=");
        assert_eq!(base64_encode(b"foobar"), "Zm9vYmFy");
    }

    #[test]
    fn connection_roundtrips_without_secret_fields() {
        let c = S3Connection {
            id: "abc".into(),
            name: "prod".into(),
            region: "us-east-1".into(),
            endpoint: None,
            force_path_style: false,
            bucket: Some("data".into()),
        };
        let json = serde_json::to_string(&c).unwrap();
        assert!(!json.contains("secret"));
        assert!(!json.contains("access_key"));
        let back: S3Connection = serde_json::from_str(&json).unwrap();
        assert_eq!(back, c);
    }
}
