/// List configured connections (metadata only; no secrets).
#[tauri::command]
pub fn s3_list_connections(
    app: AppHandle,
    state: tauri::State<'_, S3State>,
) -> Result<Vec<S3Connection>, String> {
    with_conns(&app, &state, |list| list.clone())
}

/// Create or update a connection. `access_key_id`/`secret_access_key` are
/// written to the OS secret store; the rest is persisted as metadata.
#[tauri::command]
pub async fn s3_save_connection(
    app: AppHandle,
    state: tauri::State<'_, S3State>,
    secrets: tauri::State<'_, SecretsState>,
    conn: S3Connection,
    access_key_id: String,
    secret_access_key: String,
    session_token: Option<String>,
) -> Result<(), String> {
    let secret = S3Secret {
        access_key_id,
        secret_access_key,
        session_token,
    };
    let blob = serde_json::to_string(&secret).map_err(|e| e.to_string())?;
    super::secrets::secrets_set(
        app.clone(),
        secrets.clone(),
        SECRET_SERVICE.to_string(),
        conn.id.clone(),
        blob,
    )
    .await?;

    let snapshot = with_conns(&app, &state, |list| {
        if let Some(slot) = list.iter_mut().find(|c| c.id == conn.id) {
            *slot = conn.clone();
        } else {
            list.push(conn.clone());
        }
        list.clone()
    })?;
    write_meta(&app, &snapshot)
}

/// Delete a connection and its stored credentials.
#[tauri::command]
pub async fn s3_delete_connection(
    app: AppHandle,
    state: tauri::State<'_, S3State>,
    secrets: tauri::State<'_, SecretsState>,
    id: String,
) -> Result<(), String> {
    super::secrets::secrets_delete(
        app.clone(),
        secrets.clone(),
        SECRET_SERVICE.to_string(),
        id.clone(),
    )
    .await?;
    let snapshot = with_conns(&app, &state, |list| {
        list.retain(|c| c.id != id);
        list.clone()
    })?;
    write_meta(&app, &snapshot)
}

